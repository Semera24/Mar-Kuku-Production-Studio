"""Bouncing Karaoke Sing-Along Subtitle Engine (Cocomelon / Disney Style).

Generates word-by-word synchronized subtitles:
- Advanced SubStation Alpha (.ass) with {\\k...} karaoke highlighting tags.
- Standard YouTube captions (.srt).
- CapCut Desktop timeline text clips for draft_content.json.
- FFmpeg burn-in video filters.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


class KaraokeSubtitleGenerator:
    """Generates word-level karaoke animated subtitles and CapCut text elements."""

    ASS_HEADER_TEMPLATE = """[Script Info]
; Script generated by Mar & Kuku Production Studio
Title: Mar & Kuku 16:9 Sing-Along Karaoke
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: KaraokeDefault,Arial,76,&H00FFFFFF,&H0014E5FF,&H000F172A,&H80000000,-1,0,0,0,100,100,2,0,1,6,4,2,60,60,95,1
Style: InteractiveQuestion,Arial,84,&H0076F5FF,&H0022C55E,&H000F172A,&H80000000,-1,0,0,0,105,105,2,0,1,7,5,2,60,60,110,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    @staticmethod
    def _format_ass_time(seconds: float) -> str:
        """Formats float seconds into ASS timestamp: H:MM:SS.CS (centiseconds)."""
        hrs = int(seconds // 3600)
        mins = int((seconds % 3600) // 60)
        secs = int(seconds % 60)
        centis = int(round((seconds - int(seconds)) * 100))
        if centis >= 100:
            centis = 99
        return f"{hrs}:{mins:02d}:{secs:02d}.{centis:02d}"

    @staticmethod
    def _format_srt_time(seconds: float) -> str:
        """Formats float seconds into SRT timestamp: HH:MM:SS,mmm."""
        hrs = int(seconds // 3600)
        mins = int((seconds % 3600) // 60)
        secs = int(seconds % 60)
        millis = int(round((seconds - int(seconds)) * 1000))
        if millis >= 1000:
            millis = 999
        return f"{hrs:02d}:{mins:02d}:{secs:02d},{millis:03d}"

    def generate_subtitles(
        self,
        cues: list[dict[str, Any]],
        output_dir: Path,
        stem_name: str = "karaoke_subtitles",
    ) -> dict[str, Any]:
        """Generates synchronized .ass and .srt karaoke subtitles from timed cues.

        Each cue is a dict with:
          - start: float seconds
          - end: float seconds
          - text: str (e.g. "Look at the red apple! Crunch crunch!")
          - words: optional list of (word, duration_centiseconds)
          - is_interactive: bool (for 4s response hold cues)
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        ass_path = output_dir / f"{stem_name}.ass"
        srt_path = output_dir / f"{stem_name}.srt"

        ass_lines = [self.ASS_HEADER_TEMPLATE]
        srt_lines = []

        for idx, cue in enumerate(cues, start=1):
            start_sec = float(cue["start"])
            end_sec = float(cue["end"])
            text = str(cue["text"]).strip()
            is_interactive = bool(cue.get("is_interactive", False))
            style = "InteractiveQuestion" if is_interactive else "KaraokeDefault"

            # 1. ASS Karaoke line
            words = cue.get("words")
            if words:
                # Built with {\k...} tags
                # e.g. {\k40}Look {\k30}at {\k20}the {\k50}red {\k60}apple!
                karaoke_text = "".join(f"{{\\k{int(dur)}}}{w} " for w, dur in words).strip()
            else:
                # Synthesize word durations evenly across cue duration
                raw_words = text.split()
                total_cs = max(10, int((end_sec - start_sec) * 100))
                per_word_cs = max(15, total_cs // max(1, len(raw_words)))
                karaoke_text = "".join(f"{{\\k{per_word_cs}}}{w} " for w in raw_words).strip()

            ass_start = self._format_ass_time(start_sec)
            ass_end = self._format_ass_time(end_sec)
            ass_lines.append(f"Dialogue: 0,{ass_start},{ass_end},{style},,0,0,0,,{karaoke_text}\n")

            # 2. Standard SRT entry
            srt_start = self._format_srt_time(start_sec)
            srt_end = self._format_srt_time(end_sec)
            srt_lines.append(f"{idx}\n{srt_start} --> {srt_end}\n{text}\n\n")

        ass_path.write_text("".join(ass_lines), encoding="utf-8")
        srt_path.write_text("".join(srt_lines), encoding="utf-8")

        return {
            "ass_path": str(ass_path),
            "srt_path": str(srt_path),
            "cue_count": len(cues),
            "status": "generated",
        }

    def convert_to_capcut_text_track(
        self,
        cues: list[dict[str, Any]],
        fps: int = 30,
    ) -> list[dict[str, Any]]:
        """Converts cues into native CapCut Desktop draft text items for draft_content.json."""
        text_clips = []
        for idx, cue in enumerate(cues, start=1):
            start_sec = float(cue["start"])
            end_sec = float(cue["end"])
            text = str(cue["text"]).strip()
            duration_sec = end_sec - start_sec
            is_interactive = bool(cue.get("is_interactive", False))

            # CapCut microsecond timing (1 sec = 1,000,000 us)
            start_us = int(start_sec * 1_000_000)
            duration_us = int(duration_sec * 1_000_000)

            clip = {
                "id": f"subtitle-text-{idx:04d}",
                "type": "text",
                "content": text,
                "target_timerange": {
                    "duration": duration_us,
                    "start": start_us,
                },
                "font_size": 18.0 if is_interactive else 15.0,
                "text_color": "#76F5FF" if is_interactive else "#FFFFFF",
                "stroke_color": "#0F172A",
                "stroke_width": 3.0,
                "alignment": 2,  # Center bottom
                "position": {"x": 0.0, "y": -0.78},
                "animation": {
                    "in_animation": "bounce_in" if is_interactive else "fade_in",
                    "duration": 300_000,  # 0.3s
                },
            }
            text_clips.append(clip)
        return text_clips

    def build_ffmpeg_burn_filter(self, ass_path: Path) -> str:
        """Returns the FFmpeg video filter argument to burn ASS karaoke subtitles into an MP4."""
        # Escape path for FFmpeg filter syntax
        escaped_path = str(ass_path.resolve()).replace("\\", "/").replace(":", "\\:")
        return f"ass='{escaped_path}'"
